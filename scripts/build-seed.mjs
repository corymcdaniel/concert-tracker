// Writes the seed migration from shows.json and info.json.
// Only needed if the seed is rebuilt before the first deploy; once applied,
// the database is the source of truth and this migration never runs again.
//   node scripts/build-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url);
const shows = JSON.parse(readFileSync(new URL("public/shows.json", root), "utf8"));
const info = JSON.parse(readFileSync(new URL("public/info.json", root), "utf8"));
const lit = (v) => {
  const s = JSON.stringify(v);
  if (s.includes("$seed$")) throw new Error("Seed data contains the $seed$ delimiter");
  return `$seed$${s}$seed$::jsonb`;
};

const sql = `-- Generated by scripts/build-seed.mjs from shows.json and info.json.
-- Loads the show list and artist/venue details. Runs before the change log
-- exists, so the seed isn't recorded as ${shows.length} separate changes.

INSERT INTO shows (id, artist, venue, city, state, country, date, type, notes, sort_order)
SELECT s.id, s.artist, COALESCE(s.venue, ''), COALESCE(s.city, ''), s.state, s.country,
       s.date, COALESCE(s.type, 'Music'), COALESCE(s.notes, ''), e.ord
FROM jsonb_array_elements(${lit(shows)}) WITH ORDINALITY AS e(item, ord),
     jsonb_to_record(e.item) AS s(id text, artist text, venue text, city text, state text,
                                 country text, date date, type text, notes text);

INSERT INTO artists (name, info)
SELECT key, NULLIF(value, 'null'::jsonb) FROM jsonb_each(${lit(info.artists || {})});

INSERT INTO venues (key, info)
SELECT key, NULLIF(value, 'null'::jsonb) FROM jsonb_each(${lit(info.venues || {})});
`;

writeFileSync(new URL("netlify/database/migrations/0002_seed_data.sql", root), sql);
console.log(`Seed: ${shows.length} shows, ${Object.keys(info.artists || {}).length} artists, ${Object.keys(info.venues || {}).length} venues`);
